def parse_skill_txt(path):
    """Return dict with keys TRAIN/VAL/TEST/OVERALL each holding metric dict."""
    txt = Path(path).read_text()
    result = {}
    for section in ("TRAIN", "VAL", "TEST", "OVERALL"):
        pattern = rf"{section}.*?POD=([\d.nan]+)\s+FAR=([\d.nan]+)\s+CSI=([\d.nan]+)\s+ETS=([\d.nan]+)\s+r=([\d.nan-]+)"
        m = re.search(pattern, txt, re.DOTALL)
        if m:
            result[section] = {
                "POD": float(m.group(1)),
                "FAR": float(m.group(2)),
                "CSI": float(m.group(3)),
                "ETS": float(m.group(4)),
                "r":   float(m.group(5)),
            }
        # parse years
        m2 = re.search(rf"{section}\s+years=(\[.*?\])", txt)
        if m2 and section in result:
            result[section]["years"] = eval(m2.group(1))
    return result


def load_predictions(exp, seed=42):
    """Load predictions.npz for a given experiment and seed."""
    if seed == 42:
        folder = BASE / exp / "eval_results"
    else:
        folder = BASE / f"{exp}_seed{seed}" / "eval_results"
    npz = folder / "predictions.npz"
    if not npz.exists():
        return None
    d = np.load(npz, allow_pickle=True)
    return {k: d[k] for k in d.files}


def get_metrics(exp, seeds=(42,), split="TEST"):
    """Aggregate metrics across seeds. Returns (mean_dict, std_dict)."""
    rows = []
    for s in seeds:
        if s == 42:
            txt = BASE / exp / "eval_results" / "skill_scores.txt"
        else:
            txt = BASE / f"{exp}_seed{s}" / "eval_results" / "skill_scores.txt"
        if not txt.exists():
            print(f"  [WARN] missing: {txt}")
            continue
        parsed = parse_skill_txt(txt)
        if split in parsed:
            rows.append(parsed[split])
    if not rows:
        return None, None
    keys = ["POD", "FAR", "CSI", "ETS", "r"]
    mean = {k: np.mean([r[k] for r in rows]) for k in keys}
    std  = {k: np.std( [r[k] for r in rows]) for k in keys}
    return mean, std


