# Figure 5 — Per-year skill (TbotAtm seed=42)
# ---------------------------------------------------------------------------

def fig_peryear_skill(seeds, out_dir):
    txt = BASE / "TbotAtm" / "eval_results" / "skill_scores.txt"
    if not txt.exists():
        print("  [SKIP] fig_peryear_skill — skill_scores.txt not found")
        return

    lines = txt.read_text().splitlines()
    rows = []
    in_table = False
    for line in lines:
        if line.strip().startswith("Year"):
            in_table = True
            continue
        if in_table and line.strip():
            parts = line.split()
            if len(parts) >= 7:
                try:
                    yr   = int(parts[0])
                    sp   = parts[1]
                    pod  = float(parts[3])
                    far  = float(parts[4])
                    ets  = float(parts[6])
                    r    = float(parts[7])
                    rows.append((yr, sp, pod, far, ets, r))
                except (ValueError, IndexError):
                    continue

    if not rows:
        print("  [SKIP] fig_peryear_skill — per-year table empty (re-run skill_scores.py)")
        return

    yr_arr  = np.array([r[0] for r in rows])
    sp_arr  = np.array([r[1] for r in rows])
    ets_arr = np.array([r[4] for r in rows])
    r_arr   = np.array([r[5] for r in rows])
    bar_colors = [SPLIT_COLORS.get(s, "gray") for s in sp_arr]

    with plt.rc_context(POSTER_RC):
        fig, axes = plt.subplots(2, 1, figsize=(14, 7), sharex=True)
        legend_patches = [mpatches.Patch(color=c, label=s.capitalize())
                          for s, c in SPLIT_COLORS.items()]

        ax = axes[0]
        ax.bar(yr_arr, ets_arr, color=bar_colors, alpha=0.85, width=0.7)
        ax.axhline(0, color="k", lw=0.8)
        ax.set_ylabel("ETS")
        ax.set_title("Per-year skill — TbotAtm (7-day lead, threshold: to_anom > 0)")
        ax.legend(handles=legend_patches, fontsize=10, ncol=3)
        ax.grid(axis="y", alpha=0.3)

        ax = axes[1]
        ax.bar(yr_arr, r_arr, color=bar_colors, alpha=0.85, width=0.7)
        ax.set_ylabel("Pearson r")
        ax.set_xlabel("Year")
        ax.legend(handles=legend_patches, fontsize=10, ncol=3)
        ax.grid(axis="y", alpha=0.3)

        plt.tight_layout()
        p = out_dir / "fig_peryear_skill.png"
        fig.savefig(p, dpi=150, bbox_inches="tight")
        plt.close(fig)
        print(f"Saved: {p}")


