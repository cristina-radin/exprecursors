def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output_dir", default="poster_figures")
    parser.add_argument("--seeds", nargs="+", type=int, default=[42],
                        help="Seeds to aggregate for TbotAtm (default: 42)")
    parser.add_argument("--exp_dir", default="split_blockyear",
                        help="Base directory for experiments (default: split_blockyear)")
    args = parser.parse_args()

    global BASE
    BASE = Path(args.exp_dir)

    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    seeds = tuple(args.seeds)
    print(f"Seeds: {seeds}")
    print(f"Output: {out_dir}\n")

    fig_ablation(seeds, out_dir)
    fig_metrics_table(seeds, out_dir)
    fig_scatter_test(seeds, out_dir)
    fig_timeseries_test(seeds, out_dir)
    fig_peryear_skill(seeds, out_dir)

    print(f"\nAll poster figures saved to: {out_dir}/")


if __name__ == "__main__":
    main()
